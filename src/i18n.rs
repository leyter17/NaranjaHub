use serde::{Deserialize, Serialize};

#[derive(Clone, Copy, Debug, Default, PartialEq, Eq, Serialize, Deserialize)]
pub enum Lang {
    #[default]
    Es,
    En,
}

impl Lang {
    pub fn strings(self) -> &'static Strings {
        match self {
            Lang::Es => &ES,
            Lang::En => &EN,
        }
    }

    pub fn all() -> [Lang; 2] {
        [Lang::Es, Lang::En]
    }
}

